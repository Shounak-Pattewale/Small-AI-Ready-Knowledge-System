import time
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # so `import _answerability`/`_shared`/etc. work either way

import _answerability as ans
import _ollama_grounded_qa as top1qa
import _ollama_top3_grounded_qa as top3qa
import _shared
from knowledge_system.retrieval.embedding import EmbeddingRetriever
from knowledge_system.storage import load_chunks

_CHUNKS_PATH = Path(__file__).resolve().parent.parent.parent / "storage" / "chunks.json"
_EMBEDDINGS_PATH = Path(__file__).resolve().parent.parent.parent / "storage" / "embeddings.npy"
_MANIFEST_PATH = Path(__file__).resolve().parent.parent.parent / "storage" / "embeddings_manifest.json"
_QUESTIONS_PATH = Path(__file__).resolve().parent.parent / "datasets" / "questions.json"
_BLIND_PATH = Path(__file__).resolve().parent.parent / "datasets" / "fresh_blind_test_questions.json"

# Recorded in docs/EVALUATION_HISTORY.md Section 27 (the original Top-1 Ollama Cloud experiment) -
# used only as a printed cross-check that this run's re-derived Top-1 numbers still match.
_PUBLISHED_TOP1_BASELINE = {
    "development": ans.Confusion(true_accept=25, false_abstain=5, true_abstain=13, false_accept=2),
    "heldout": ans.Confusion(true_accept=9, false_abstain=1, true_abstain=8, false_accept=2),
    "blind-origin": ans.Confusion(true_accept=14, false_abstain=1, true_abstain=11, false_accept=4),
}

_PRODUCTION_FAILURE_QUESTIONS = [
    "What expenses can I claim when travelling for work?",
    "Can I work from home whenever I want?",
]


@dataclass
class Top3Record:
    q: dict
    top3_results: list  # up to 3 SearchResult, Granite rank order
    top1_structured: top1qa.StructuredResult | None
    top1_error: str | None
    top1_prompt_tokens: int | None
    top1_output_tokens: int | None
    top3_structured: top3qa.StructuredResultTop3 | None
    top3_error: str | None
    top3_prompt_tokens: int | None
    top3_output_tokens: int | None

    @property
    def top1_decision(self) -> str:
        if self.top1_error is not None or self.top1_structured is None or not self.top1_structured.valid:
            return "ERROR"
        return "ANSWER" if self.top1_structured.answerable else "ABSTAIN"

    @property
    def top3_decision(self) -> str:
        if self.top3_error is not None or self.top3_structured is None or not self.top3_structured.valid:
            return "ERROR"
        return "ANSWER" if self.top3_structured.answerable else "ABSTAIN"


def evaluate_question(question_text: str, retriever: EmbeddingRetriever, run_top1: bool = True) -> Top3Record:
    """ONE Granite Top-3 retrieval feeds both calls. `run_top1=False` skips the redundant Top-1
    call for the two already-diagnosed production-failure questions (their Top-1 result is
    already known from the prior diagnostic task)."""
    results = retriever.search(question_text, top_k=3)
    evidences = [r.chunk.text for r in results]

    top1_structured, top1_error, t1p, t1o = None, None, None, None
    if run_top1:
        try:
            body1 = top1qa.call_ollama_chat_full(question_text, results[0].chunk.text)
        except top1qa.OllamaAPIError as exc:
            top1_error = str(exc)
        else:
            message = body1.get("message") if isinstance(body1, dict) else None
            content1 = message.get("content") if isinstance(message, dict) else None
            if content1 is None:
                top1_error = "response missing message.content"
            else:
                top1_structured = top1qa.parse_structured_output(content1)
                t1p, t1o = body1.get("prompt_eval_count"), body1.get("eval_count")

    top3_structured, top3_error, t3p, t3o = None, None, None, None
    try:
        body3 = top3qa.call_ollama_chat_top3_full(question_text, evidences)
    except top3qa.OllamaAPIError as exc:
        top3_error = str(exc)
    else:
        message = body3.get("message") if isinstance(body3, dict) else None
        content3 = message.get("content") if isinstance(message, dict) else None
        if content3 is None:
            top3_error = "response missing message.content"
        else:
            top3_structured = top3qa.parse_structured_output_top3(content3)
            t3p, t3o = body3.get("prompt_eval_count"), body3.get("eval_count")

    return Top3Record(
        q={"question": question_text}, top3_results=results,
        top1_structured=top1_structured, top1_error=top1_error, top1_prompt_tokens=t1p, top1_output_tokens=t1o,
        top3_structured=top3_structured, top3_error=top3_error, top3_prompt_tokens=t3p, top3_output_tokens=t3o,
    )


def run_formal_split(label: str, questions: list[dict], retriever: EmbeddingRetriever) -> list[Top3Record]:
    records = []
    for q in questions:
        record = evaluate_question(q["question"], retriever)
        record.q = q
        records.append(record)

    labels = [r.q["answerable"] for r in records]

    top1_scored = [r for r in records if r.top1_decision != "ERROR"]
    top1_confusion = ans.confusion_counts([r.q["answerable"] for r in top1_scored], [r.top1_decision == "ANSWER" for r in top1_scored])
    top1_errors = len(records) - len(top1_scored)

    top3_scored = [r for r in records if r.top3_decision != "ERROR"]
    top3_confusion = ans.confusion_counts([r.q["answerable"] for r in top3_scored], [r.top3_decision == "ANSWER" for r in top3_scored])
    top3_errors = len(records) - len(top3_scored)

    print(f"\n{'=' * 70}\n{label} (n={len(records)})\n{'=' * 70}")
    print(f"TOP-1 (re-derived this run, errors={top1_errors}): TA={top1_confusion.true_accept} FAb={top1_confusion.false_abstain} "
          f"TAb={top1_confusion.true_abstain} FAc={top1_confusion.false_accept}  "
          f"recall={top1_confusion.answerable_recall:.2%} rejection={top1_confusion.unanswerable_rejection_rate:.2%} "
          f"balanced={top1_confusion.balanced_accuracy:.2%}")
    published = _PUBLISHED_TOP1_BASELINE[label.lower().replace(" ", "-")]
    matches = (top1_confusion.true_accept, top1_confusion.false_abstain, top1_confusion.true_abstain, top1_confusion.false_accept) == \
              (published.true_accept, published.false_abstain, published.true_abstain, published.false_accept)
    print(f"Matches published Top-1 baseline: {'YES' if matches else 'NO - INVESTIGATE'}")
    print(f"\nTOP-3 (errors={top3_errors}): TA={top3_confusion.true_accept} FAb={top3_confusion.false_abstain} "
          f"TAb={top3_confusion.true_abstain} FAc={top3_confusion.false_accept}  "
          f"recall={top3_confusion.answerable_recall:.2%} rejection={top3_confusion.unanswerable_rejection_rate:.2%} "
          f"balanced={top3_confusion.balanced_accuracy:.2%}")

    return records


def print_regression_analysis(label: str, records: list[Top3Record]) -> tuple[int, int, int]:
    print(f"\n{'-' * 70}\n{label}: TOP-1 vs TOP-3 CHANGED DECISIONS\n{'-' * 70}")
    improvements = regressions = neutral = 0
    for r in records:
        if r.top1_decision == r.top3_decision:
            continue
        label_true = r.q["answerable"]
        top1_correct = (r.top1_decision == "ANSWER") == label_true if r.top1_decision != "ERROR" else False
        top3_correct = (r.top3_decision == "ANSWER") == label_true if r.top3_decision != "ERROR" else False

        if top3_correct and not top1_correct:
            classification = "IMPROVEMENT"
            improvements += 1
        elif top1_correct and not top3_correct:
            classification = "REGRESSION"
            regressions += 1
        else:
            classification = "NEUTRAL / BENCHMARK-NUANCE"
            neutral += 1

        evidence_id = r.top3_structured.evidence_id if (r.top3_structured and r.top3_structured.valid) else None
        selected = r.top3_results[evidence_id - 1] if evidence_id else None
        top3_sources = [f"{i+1}:{res.chunk.source}/{res.chunk.section}" for i, res in enumerate(r.top3_results)]

        flag = " <-- unsupported incorrectly answered" if (not label_true and r.top3_decision == "ANSWER" and r.top1_decision != "ANSWER") else ""
        print(
            f"\n{r.q.get('id', '?')}: {r.q['question']}{flag}\n"
            f"  expected_answerable={label_true}\n"
            f"  Top-1: {r.top1_decision}   Top-3: {r.top3_decision}\n"
            f"  Top-3 candidates: {top3_sources}\n"
            f"  selected evidence_id={evidence_id}  source={selected.chunk.source if selected else None}  section={selected.chunk.section if selected else None}\n"
            f"  Top-3 answer={r.top3_structured.answer if r.top3_structured else None!r}\n"
            f"  classification={classification}"
        )
    print(f"\n{label} totals: improvements={improvements} regressions={regressions} neutral={neutral}")
    return improvements, regressions, neutral


def print_provenance_validation(label: str, records: list[Top3Record]) -> None:
    print(f"\n{'-' * 70}\n{label}: PROVENANCE VALIDATION (Top-3 answerable results)\n{'-' * 70}")
    answerable_attempts = [r for r in records if r.top3_error is None and r.top3_structured is not None]
    answerable_valid = [r for r in answerable_attempts if r.top3_structured.valid]
    malformed = len(answerable_attempts) - len(answerable_valid)

    true_answerable_valid = [r for r in answerable_valid if r.top3_structured.answerable]
    valid_evidence_id_count = sum(1 for r in true_answerable_valid if r.top3_structured.evidence_id in (1, 2, 3))
    print(f"Total Top-3 attempts: {len(records)}  malformed/parse-failed: {malformed}")
    print(f"Answerable=true results: {len(true_answerable_valid)}")
    print(f"Valid evidence_id rate (of answerable=true, already enforced by the parser): "
          f"{valid_evidence_id_count}/{len(true_answerable_valid)} = "
          f"{(valid_evidence_id_count / len(true_answerable_valid) if true_answerable_valid else 0):.2%}")


def main() -> None:
    chunks = load_chunks(_CHUNKS_PATH)
    retriever = EmbeddingRetriever()
    retriever.load_index(chunks, _EMBEDDINGS_PATH, _MANIFEST_PATH)

    all_questions = _shared.load_questions(_QUESTIONS_PATH)
    dev_questions = ans.filter_by_split(all_questions, "development")
    heldout_questions = ans.filter_by_split(all_questions, "heldout")
    blind_questions = _shared.load_questions(_BLIND_PATH)

    print(f"Development: {len(dev_questions)}  Heldout: {len(heldout_questions)}  Blind-origin: {len(blind_questions)}")

    eval_start = time.monotonic()
    all_records: list[Top3Record] = []
    total_improvements = total_regressions = total_neutral = 0
    for label, questions in [("development", dev_questions), ("heldout", heldout_questions), ("blind-origin", blind_questions)]:
        records = run_formal_split(label.upper(), questions, retriever)
        i, reg, n = print_regression_analysis(label.upper(), records)
        total_improvements += i
        total_regressions += reg
        total_neutral += n
        print_provenance_validation(label.upper(), records)
        all_records.extend(records)
    eval_seconds = time.monotonic() - eval_start

    print(f"\n{'=' * 70}\nTOTAL REGRESSION SUMMARY (all formal splits)\n{'=' * 70}")
    print(f"Improvements: {total_improvements}  Regressions: {total_regressions}  Neutral/benchmark-nuance: {total_neutral}")

    # ---------- token/evidence-size comparison ----------
    top1_calls = [r for r in all_records if r.top1_prompt_tokens is not None]
    top3_calls = [r for r in all_records if r.top3_prompt_tokens is not None]
    top1_prompt_total = sum(r.top1_prompt_tokens for r in top1_calls)
    top3_prompt_total = sum(r.top3_prompt_tokens for r in top3_calls)
    top1_output_total = sum(r.top1_output_tokens for r in top1_calls)
    top3_output_total = sum(r.top3_output_tokens for r in top3_calls)
    top1_evidence_chars = sum(len(r.top3_results[0].chunk.text) for r in all_records)
    top3_evidence_chars = sum(sum(len(res.chunk.text) for res in r.top3_results) for r in all_records)

    print(f"\n{'=' * 70}\nTOKEN / EVIDENCE-SIZE COMPARISON\n{'=' * 70}")
    print(f"Top-1 prompt tokens total: {top1_prompt_total}  (n={len(top1_calls)})")
    print(f"Top-3 prompt tokens total: {top3_prompt_total}  (n={len(top3_calls)})")
    if top1_prompt_total:
        print(f"Prompt-token multiplier (Top-3 / Top-1): {top3_prompt_total / top1_prompt_total:.2f}x")
    print(f"Top-1 output tokens total: {top1_output_total}")
    print(f"Top-3 output tokens total: {top3_output_total}")
    print(f"Top-1 evidence characters total (Top-1 chunk only, summed over all questions): {top1_evidence_chars}")
    print(f"Top-3 evidence characters total (up to 3 chunks, summed over all questions): {top3_evidence_chars}")
    if top1_evidence_chars:
        print(f"Evidence-character multiplier (Top-3 / Top-1): {top3_evidence_chars / top1_evidence_chars:.2f}x")
    print(f"Formal-split evaluation runtime ({len(all_records)} questions, {len(all_records) * 2} calls): {eval_seconds:.2f}s")

    # ---------- the two production-failure questions (diagnostic only, NOT merged into benchmark) ----------
    print(f"\n{'=' * 70}\nPRODUCTION-FAILURE DIAGNOSTIC (Top-3 only - Top-1 result already known)\n{'=' * 70}")
    for question in _PRODUCTION_FAILURE_QUESTIONS:
        record = evaluate_question(question, retriever, run_top1=False)
        print(f"\nQuestion: {question}")
        for i, res in enumerate(record.top3_results, start=1):
            excerpt = res.chunk.text[:160].replace("\n", " ")
            print(f"  EVIDENCE {i}: source={res.chunk.source}  section={res.chunk.section}  sim={res.score:.4f}\n    {excerpt!r}")
        if record.top3_error:
            print(f"  TOP-3 API ERROR: {record.top3_error}")
        elif not record.top3_structured.valid:
            print(f"  TOP-3 MALFORMED: {record.top3_structured.error}  raw={record.top3_structured.raw!r}")
        else:
            s = record.top3_structured
            evidence_id = s.evidence_id
            selected = record.top3_results[evidence_id - 1] if evidence_id else None
            print(f"  answerable={s.answerable}  answer={s.answer!r}  evidence_id={evidence_id}")
            if selected:
                print(f"  mapped source={selected.chunk.source}  section={selected.chunk.section}  page={selected.chunk.page}")


if __name__ == "__main__":
    main()
