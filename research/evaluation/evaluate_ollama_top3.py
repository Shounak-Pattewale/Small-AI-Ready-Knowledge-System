"""EXPERIMENTAL ONLY: Granite Top-3 evidence blocks + Ollama Cloud, evidence_id provenance.

Tests whether giving Ollama three labeled evidence blocks (instead of the
production Top-1 chunk) improves answerable recall / reduces false accepts,
while keeping provenance application-controlled via a validated
`evidence_id` the model must return (1/2/3/null) - never a filename,
section, or page generated by the model itself.

For every formal-split question this script makes TWO real Ollama calls
per question: the SAME Top-1 call the original Ollama Cloud experiment
made (evaluation/_ollama_grounded_qa.py, unmodified), and the new Top-3
call (_ollama_top3_grounded_qa.py) - both against the exact same Granite
retrieval, so the two decisions are directly comparable per question, not
just at the aggregate-metric level. This is the only way to produce the
required per-question regression analysis; the original experiment's
individual decisions were never persisted anywhere reusable.

Reuses the SAME production Granite index (storage/chunks.json,
storage/embeddings.npy) unmodified - retrieval itself is not touched.
Does not modify src/knowledge_system/, app.py, cli.py, ratelimit.py, or
the corpus.

Run from the project root:
    venv/bin/python research/evaluation/evaluate_ollama_top3.py
"""

